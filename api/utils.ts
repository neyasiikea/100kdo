// src/utils.ts — Hash, slug, and category inference

export async function hashQuery(q: string): Promise<string> {
  const data = new TextEncoder().encode(q.trim().toLowerCase());
  const buf = await crypto.subtle.digest('SHA-256', data);
  return Array.from(new Uint8Array(buf)).map(b => b.toString(16).padStart(2,'0')).join('').slice(0,16);
}

export function generateSlug(title: string): string {
  return title.replace(/[^a-zA-Z0-9一-鿿\s-]/g,'').trim().replace(/\s+/g,'-').toLowerCase().slice(0,80);
}

export function generateId(): string {
  return `gen_${Date.now()}_${Math.random().toString(36).slice(2,8)}`;
}

